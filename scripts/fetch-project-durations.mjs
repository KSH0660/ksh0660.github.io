// scripts/fetch-project-durations.mjs
// Pre-build script: reads repo info from data/projects.ts, fetches GitHub dates,
// and generates data/projectDurations.ts

import fs from "node:fs";
import path from "node:path";

/**
 * Parse data/projects.ts to extract project IDs and their repo fields.
 * Uses simple regex matching — no TypeScript parser dependency needed.
 */
function parseProjectRepos() {
  const filePath = path.join(process.cwd(), "data", "projects.ts");
  const source = fs.readFileSync(filePath, "utf-8");

  const projects = [];
  const blockRe = /\{[^}]*id:\s*"([^"]+)"[^}]*\}/gs;

  for (const block of source.matchAll(blockRe)) {
    const text = block[0];
    const id = block[1];
    const ownerMatch = text.match(/owner:\s*"([^"]+)"/);
    const nameMatch = text.match(/name:\s*"([^"]+)"/);

    if (ownerMatch && nameMatch) {
      projects.push({ id, owner: ownerMatch[1], repo: nameMatch[1] });
    }
  }

  return projects;
}

async function fetchDuration(owner, repo) {
  const repoRes = await fetch(
    `https://api.github.com/repos/${owner}/${repo}`,
    { headers: { "User-Agent": "portfolio-build" } },
  );
  if (!repoRes.ok) throw new Error(`Repo API ${repoRes.status}`);
  const repoData = await repoRes.json();
  const startDate = repoData.created_at;

  const commitsRes = await fetch(
    `https://api.github.com/repos/${owner}/${repo}/commits?per_page=1`,
    { headers: { "User-Agent": "portfolio-build" } },
  );
  if (!commitsRes.ok) throw new Error(`Commits API ${commitsRes.status}`);
  const commitsData = await commitsRes.json();
  const endDate = commitsData[0].commit.committer.date;

  const totalDays = Math.max(
    1,
    Math.ceil(
      (new Date(endDate).getTime() - new Date(startDate).getTime()) / 86_400_000,
    ),
  );

  return { startDate, endDate, totalDays };
}

async function main() {
  const projects = parseProjectRepos();

  if (projects.length === 0) {
    console.log("No projects with repo field found — skipping fetch.");
  }

  const durations = {};

  for (const { id, owner, repo } of projects) {
    try {
      durations[id] = await fetchDuration(owner, repo);
      console.log(`Fetched duration for ${id}: ${durations[id].totalDays} days`);
    } catch (err) {
      console.warn(`Failed to fetch duration for ${id}: ${err.message}`);
    }
  }

  const content = `// AUTO-GENERATED by scripts/fetch-project-durations.mjs — do not edit
import type { ProjectDuration } from "@/data/projects";

export const projectDurations: Record<string, ProjectDuration> = ${JSON.stringify(durations, null, 2)};
`;

  const outPath = path.join(process.cwd(), "data", "projectDurations.ts");
  fs.writeFileSync(outPath, content, "utf-8");
  console.log(`Wrote ${outPath}`);
}

main().catch((err) => {
  console.error("fetch-project-durations failed:", err);
  // Exit 0 so the build continues even if this fails
  process.exit(0);
});
